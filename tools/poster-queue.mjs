const tbilisiUnix = (d, h, m) =>
  Math.floor(Date.UTC(d.getUTCFullYear(), d.getUTCMonth(), d.getUTCDate(), h - TZ, m) / 1000);

const DAYS = ['კვი', 'ორშ', 'სამ', 'ოთხ', 'ხუთ', 'პარ', 'შაბ'];
const stamp = (t) => {
  const d = new Date((t + TZ * 3600) * 1000);
  const hh = String(d.getUTCHours()).padStart(2, '0');
  const mm = String(d.getUTCMinutes()).padStart(2, '0');
  return `${d.toISOString().slice(0, 10)} ${DAYS[d.getUTCDay()]} ${hh}:${mm}`;
};

// Every Thursday slot from `from` onwards, whether or not it fits the Facebook
// horizon. `taken` holds the times earlier runs already used, so a top-up run
// lands after the queue instead of on top of it.
function allSlots(from, count, taken = new Set()) {
  const out = [];
  const day = new Date(Date.UTC(from.getUTCFullYear(), from.getUTCMonth(), from.getUTCDate()));
  const now = Math.floor(Date.now() / 1000);
  while (out.length < count) {
    if (day.getUTCDay() === SLOT.dow) {
      const t = tbilisiUnix(day, SLOT.h, SLOT.m);
      // Facebook refuses anything less than 10 minutes out.
      if (t > now + 900 && !taken.has(t)) out.push(t);
    }
    day.setUTCDate(day.getUTCDate() + 1);
  }
  return out;
}

async function state() {
  if (!existsSync(STATE)) return { posted: [] };
  return JSON.parse(await readFile(STATE, 'utf8'));
}

async function creds() {
  const env = path.join(ROOT, '.env');
  if (existsSync(env)) {
    for (const line of (await readFile(env, 'utf8')).split('\n')) {
      const m = /^\s*([A-Z_]+)\s*=\s*(.*?)\s*$/.exec(line);
      if (m && !process.env[m[1]]) process.env[m[1]] = m[2].replace(/^["']|["']$/g, '');
    }
  }
  const id = process.env.FB_PAGE_ID;
  const token = process.env.FB_PAGE_TOKEN;
  if (!id || !token) throw new Error('FB_PAGE_ID და FB_PAGE_TOKEN უნდა იყოს .env-ში');
  return { id, token };
}

async function graph(endpoint, params, method = 'GET') {
  const { token } = await creds();
  const body = new URLSearchParams({ ...params, access_token: token });
  const url = `https://graph.facebook.com/${API}/${endpoint}`;
  const res = method === 'GET'
    ? await fetch(`${url}?${body}`)
    : await fetch(url, { method, body });
  const json = await res.json();
  if (json.error) throw new Error(`${json.error.type} ${json.error.code}: ${json.error.message}`);
  return json;
}

// The whole campaign with a time against every poster. Slots already used by an
// earlier run are read back from the state file rather than recomputed, so the
// plan stays stable as the horizon moves and a top-up run cannot shift a poster
// that is already sitting in the Facebook queue.
function planAll(hist) {
  const at = {};
  for (const p of hist.posted) at[p.slug] = p.at;
  const left = POSTERS.filter((p) => !at[p.slug]);
  const times = allSlots(new Date(), left.length, new Set(Object.values(at)));
  left.forEach((p, i) => { at[p.slug] = times[i]; });
  return POSTERS.map((p) => ({ ...p, at: at[p.slug] }));
}

// Neither Cloud Function has a copy of this file, so what they need is exported
// next to them and deployed with them: Instagram takes the caption and the
// image, Facebook additionally takes its own caption, the slot time, and the
// list of posters this laptop has already queued.
async function exportContent() {
  const hist = await state();
  const out = {
    generated: new Date().toISOString().slice(0, 10),
    facebookQueued: hist.posted.map((p) => p.slug),
    posters: planAll(hist).map((p) => ({
      slug: p.slug,
      title: p.title,
      image: image(p),
      at: p.at,
      caption: igCaption(p),
      fb: p.fb,
    })),
  };
  await writeFile(EXPORT, JSON.stringify(out, null, 1), 'utf8');
  console.log(`${out.posters.length} პოსტერი → ${path.relative(ROOT, EXPORT)}`);
  console.log(`Facebook-ზე უკვე დაგეგმილი: ${out.facebookQueued.length}, დანარჩენს ფუნქცია ჩადგამს.`);
}

