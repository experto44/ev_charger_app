async function main() {
  if (flag('export')) return exportContent();
  if (flag('doc')) return doc();

  if (flag('list')) {
    const { id } = await creds();
    const r = await graph(`${id}/scheduled_posts`, { fields: 'id,message,scheduled_publish_time', limit: '50' });
    if (!r.data || !r.data.length) return console.log('რიგი ცარიელია.');
    for (const p of r.data) {
      console.log(`${stamp(Number(p.scheduled_publish_time))}  ${p.id}`);
      console.log(`   ${(p.message || '').split('\n')[0].slice(0, 90)}`);
    }
    return;
  }

  if (flag('cancel')) {
    const id = arg('cancel');
    if (!id) throw new Error('--cancel <post-id>');
    await graph(String(id), {}, 'DELETE');
    return console.log(`გაუქმდა: ${id}`);
  }

  const hist = await state();
  const done = new Set(hist.posted.map((p) => p.slug));
  const queue = planAll(hist).filter((p) => !done.has(p.slug));
  if (!queue.length) return console.log('ცხრავე პოსტერი უკვე დაგეგმილია.');

  const now = Math.floor(Date.now() / 1000);
  const limit = now + HORIZON_DAYS * 86400;
  const fits = queue.filter((q) => q.at <= limit);

  const md = [
    '# პოსტერების რიგი',
    '',
    `მომზადდა ${new Date().toISOString().slice(0, 10)}. ${queue.length} პოსტი, ხუთშაბათობით, დრო თბილისის.`,
    '',
    ...queue.map((q) =>
      `- ${stamp(q.at)}  **${q.title}**  \`${q.slug}\`${q.at > limit ? '  (Facebook-ის ფანჯარას სცდება, Instagram მაინც გამოაქვეყნებს)' : ''}`),
    '',
  ].join('\n');
  await mkdir(path.dirname(QUEUE_MD), { recursive: true });
  await writeFile(QUEUE_MD, md, 'utf8');

  for (const q of queue) {
    console.log(`${stamp(q.at)}  ${q.slug}${q.at > limit ? '  [FB: ფანჯრის მიღმა]' : ''}`);
  }
  console.log(`\n→ ${path.relative(ROOT, QUEUE_MD)}`);
  console.log(`Facebook-ზე ახლა ჩაჯდება ${fits.length}/${queue.length}, დანარჩენი მოგვიანებით.`);

  if (!flag('publish')) {
    console.log('\nდაგეგმილი არაფერია, ეს dry run იყო. გასაშვებად: node tools/poster-queue.mjs --publish');
    return;
  }

  const { id } = await creds();
  const posted = [...hist.posted];
  for (const q of fits) {
    // /photos rather than /feed: the poster is the post, and a photo post keeps
    // the full 1080x1350 in the feed instead of a link card crop.
    const r = await graph(`${id}/photos`, {
      url: image(q),
      caption: q.fb,
      published: 'false',
      scheduled_publish_time: String(q.at),
    }, 'POST');
    console.log(`✓ ${stamp(q.at)}  ${q.slug}  ${r.id}`);
    posted.push({ slug: q.slug, at: q.at, id: r.id, post_id: r.post_id || null });
    await writeFile(STATE, JSON.stringify({ posted }, null, 1), 'utf8');
  }
}

main().catch((e) => { console.error(`!! ${e.message}`); process.exit(1); });
